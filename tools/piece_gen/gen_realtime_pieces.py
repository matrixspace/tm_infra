#!/usr/bin/env python3
"""Generate RealTimeApp handler/action pieces (arity 2..20).

Run: python3 tools/piece_gen/gen_realtime_pieces.py [--check]
Templates hold the reviewed two-input implementation. Requires clang-format.
--check checks without writing.
"""
import argparse
import subprocess
from pathlib import Path

HERE = Path(__file__).resolve().parent
DEST = HERE.parents[1] / 'tm_kit' / 'infra'


def handler(n):
    types = ', '.join(f'class A{i}' for i in range(n))
    variant = 'std::variant<' + ','.join(f'A{i}' for i in range(n)) + '>'
    bases = ', '.join(f'public virtual IHandler<A{i}>' for i in range(n))
    text = f'''template <{types}, class W, class Policy>
class ExecHandler<{variant}, W, Policy> : {bases}, public ExecHandlerCore<{variant}, W, Policy> {{
private:
'''
    for i in range(n):
        text += f'''    static {variant} fromA{i}(A{i} &&x) {{
        return {variant} {{std::in_place_index<{i}>, std::move(x)}};
    }}
'''
    text += 'public:\n'
    for i in range(n):
        text += f'''    void handle(TimedDataWithEnvironment<A{i}, StateT, typename StateT::TimePointType> &&data) override final {{
        this->putData(withtime_utils::pureTimedDataWithEnvironmentLift(fromA{i}, std::move(data), true));
    }}
'''
    return text + '};\n'


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--check', action='store_true')
    args = parser.parse_args()
    outputs = {'ThreadedHandler': ''.join(handler(n) for n in range(2, 21))}
    for name in ('ActionCore', 'MultiActionCore'):
        template = (HERE / (name + '.hpp.in')).read_text()
        outputs[name] = ''.join(template.replace('@TYPE_PARAMS@', ', '.join(f'class A{i}' for i in range(n)))
                               .replace('@VARIANT@', 'std::variant<' + ','.join(f'A{i}' for i in range(n)) + '>')
                               for n in range(2, 21))
    for name, content in outputs.items():
        path = DEST / f'RealTimeApp_{name}_Piece.hpp'
        content = '// Generated by tools/piece_gen/gen_realtime_pieces.py; do not edit.\n' + content
        content = subprocess.run(['clang-format', '--style=file', '--assume-filename=' + str(path)],
                                 input=content, text=True, capture_output=True, check=True).stdout
        if args.check:
            if path.read_text() != content:
                raise SystemExit(f'Out of date: {path}')
        else:
            path.write_text(content)


if __name__ == '__main__':
    main()
